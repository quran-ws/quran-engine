#!/usr/bin/env python3
"""Write the React Native package's target and selector codes from the C header.

Input
  crates/qvp-ffi/include/qvp.h      the QVP_TARGET_* and QVP_SELECTOR_* enums

Output
  packages/react-native/qvp-react-native/src/codes.ts
  packages/react-native/qvp-react-native/android/src/main/java/ws/quran/qvp/rn/Codes.kt

Each code has one camelCase name: QVP_TARGET_AYAH_RANGE is `ayahRange`. The JavaScript side
builds targets and selectors with these codes, and the Kotlin side reads them back with the
same table, so neither keeps a list of its own. `--check` writes nothing and exits 1 when a
file is out of date. scripts/check-parity.py runs the check.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "crates/qvp-ffi/include/qvp.h"
PACKAGE = ROOT / "packages/react-native/qvp-react-native"
TS_OUT = PACKAGE / "src/codes.ts"
KT_OUT = PACKAGE / "android/src/main/java/ws/quran/qvp/rn/Codes.kt"
NOTE = "Generated by scripts/gen-rn-enums.py from crates/qvp-ffi/include/qvp.h. Do not edit."
TABLES = {"TARGET": "the kind of a target", "SELECTOR": "the kind of a selector"}


def enum(prefix: str, header: str) -> list[tuple[str, int]]:
    """The QVP_<prefix>_* codes of the header, in header order, as (SUFFIX, value)."""
    for body in re.findall(r"enum\s*\{([^}]*)\}", header):
        if f"QVP_{prefix}_" not in body:
            continue
        out: list[tuple[str, int]] = []
        value = -1
        for item in body.split(","):
            m = re.match(rf"\s*QVP_{prefix}_([A-Z0-9_]+)\s*(?:=\s*(\d+))?\s*$", item)
            if not m:
                raise SystemExit(f"{HEADER}: cannot read the enum item {item.strip()!r}")
            value = int(m.group(2)) if m.group(2) else value + 1
            out.append((m.group(1), value))
        return out
    raise SystemExit(f"{HEADER}: no QVP_{prefix}_* enum")


def camel(suffix: str) -> str:
    head, *rest = suffix.lower().split("_")
    return head + "".join(p.capitalize() for p in rest)


def typescript(tables: dict[str, list[tuple[str, int]]]) -> str:
    lines = [f"// {NOTE}", ""]
    for prefix, codes in tables.items():
        lines.append(f"/** QVP_{prefix}_*: {TABLES[prefix]}, by name. */")
        lines.append(f"export const {prefix} = {{")
        lines += [f"  {camel(s)}: {v}," for s, v in codes]
        lines += ["} as const;", ""]
    return "\n".join(lines).rstrip() + "\n"


def kotlin(tables: dict[str, list[tuple[str, int]]]) -> str:
    lines = [
        f"// {NOTE}",
        "package ws.quran.qvp.rn",
        "",
        "/** The QVP_TARGET_* and QVP_SELECTOR_* codes, and each code by its JavaScript name. */",
        "internal object Codes {",
    ]
    for prefix, codes in tables.items():
        lines += [f"    const val {prefix}_{s} = {v}" for s, v in codes]
        pairs = ", ".join(f'"{camel(s)}" to {prefix}_{s}' for s, _ in codes)
        lines.append(f"    /** QVP_{prefix}_*: {TABLES[prefix]}, by name. */")
        lines.append(f"    val {prefix}S: Map<String, Int> = mapOf({pairs})")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    header = HEADER.read_text()
    tables = {prefix: enum(prefix, header) for prefix in TABLES}
    stale = []
    for path, text in ((TS_OUT, typescript(tables)), (KT_OUT, kotlin(tables))):
        current = path.read_text() if path.exists() else ""
        if current == text:
            continue
        stale.append(path.relative_to(ROOT))
        if "--check" not in argv:
            path.write_text(text)
    if "--check" in argv:
        for p in stale:
            print(f"FAIL {p} is out of date; run scripts/gen-rn-enums.py")
        return 1 if stale else 0
    for p in stale:
        print(f"wrote {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
