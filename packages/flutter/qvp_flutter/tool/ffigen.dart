// Generates lib/src/bindings.dart from crates/qvp-ffi/include/qvp.h with package:ffigen.
//
// Run from the package directory: `dart run tool/ffigen.dart`. An argument writes the
// bindings to that path instead, which scripts/check-flutter-bindings.sh uses to compare
// a fresh copy with the committed file. ffigen needs libclang: Xcode or the Command Line
// Tools on macOS, the libclang-dev package on Linux.
//
// The names keep the shape the backend was written against: a struct is the C name plus
// `C` (`QvpPageInfo` is `QvpPageInfoC`), a field is its C name in camelCase without a
// leading underscore (`n_lines` is `nLines`, `_pad` is `pad`), and a function is its C
// name without `qvp_` in camelCase (`qvp_page_load` is `pageLoad`). scripts/check-parity.py
// counts a function as bound in Flutter by that camelCase name in the backend sources.
import 'dart:io';

import 'package:ffigen/ffigen.dart';

/// `n_lines` is `nLines`, `_pad2` is `pad2`.
String camel(String snake) {
  final parts = snake
      .replaceFirst(RegExp('^_+'), '')
      .split('_')
      .where((p) => p.isNotEmpty)
      .toList();
  return parts.first +
      parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
}

Future<void> main(List<String> args) async {
  final packageRoot = Platform.script.resolve('../');
  final header = packageRoot.resolve('../../../crates/qvp-ffi/include/qvp.h');
  final out = args.isEmpty
      ? packageRoot.resolve('lib/src/bindings.dart')
      : Uri.file(File(args.first).absolute.path);

  await FfiGenerator(
    input: Input(
      entryPoints: [header],
      include: (h) => h.path.endsWith('/qvp.h'),
    ),
    output: Output(
      dart: DartOutput(path: out),
      style: const DynamicLibraryBindings(
        wrapperName: 'QvpBindings',
        wrapperDocComment:
            'The C functions of one loaded `libqvp_ffi`, each named as its C name '
            'without `qvp_`, camel-cased.',
      ),
      // The header is the documentation. Its section comments would land on whichever
      // function follows them, so the bindings carry none.
      commentType: const CommentType.none(),
      preamble:
          '// Generated by package:ffigen from crates/qvp-ffi/include/qvp.h. Do not edit.\n'
          '// Regenerate with `dart run tool/ffigen.dart` in packages/flutter/qvp_flutter.\n'
          '// scripts/check-flutter-bindings.sh fails when this file and the header differ.\n',
    ),
    visitors: [
      Visitor(
        func: (node) {
          if (node.originalName.startsWith('qvp_')) {
            node.isIncluded = true;
            node.name = camel(node.originalName.substring('qvp_'.length));
          }
        },
        struct: (node) {
          if (node.originalName.startsWith('Qvp')) {
            node.isIncluded = true;
            node.name = '${node.originalName}C';
          }
        },
        field: (node) => node.name = camel(node.name),
        param: (node) => node.name = camel(node.name),
      ),
    ],
  ).generate();

  // ffigen keeps every name unique across the whole file, so a field or a parameter that
  // shares its name with a function gets `$1`: QvpWordInfo.text would be `text$1`,
  // because of qvp_text. A field is a member of its struct class and a parameter is local
  // to its method, so the plain C name is valid Dart. Strip the suffix, so a new function
  // in the header never renames a field the backend reads.
  final file = File.fromUri(out);
  final source = file.readAsStringSync().replaceAllMapped(
    RegExp(r'\b([a-z][A-Za-z0-9]*)\$1\b'),
    (m) => m[1]!,
  );
  final left = RegExp(r'\b[a-z][A-Za-z0-9]*\$[0-9]+\b').firstMatch(source);
  if (left != null) {
    stderr.writeln(
      'ffigen named `${left[0]}` with a suffix this script does not strip; '
      'extend tool/ffigen.dart',
    );
    exit(1);
  }
  file.writeAsStringSync(source);

  // ffigen formats with the package's language floor (3.6). The package's sources, and
  // the CI format step, use the newest style.
  final format = await Process.run(Platform.resolvedExecutable, [
    'format',
    '--language-version=latest',
    out.toFilePath(),
  ]);
  if (format.exitCode != 0) {
    stderr.write(format.stderr);
    exit(format.exitCode);
  }
}
